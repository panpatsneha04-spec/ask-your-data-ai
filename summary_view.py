"""Streamlit UI for the Executive Summary tab (data comes from askyourdata.summary)."""

from __future__ import annotations

import streamlit as st

from askyourdata import charts
from askyourdata.summary import ExecutiveSummary, Section

KPIS_PER_ROW = 4
LONG_KPI_LABEL = 22  # characters; longer labels or values get a double-width card
LONG_KPI_VALUE = 8


def kpi_width(kpi) -> int:
    return 2 if len(kpi.label) > LONG_KPI_LABEL or len(kpi.value) > LONG_KPI_VALUE else 1


def kpi_rows(kpis) -> list[list]:
    """KPI cards packed into rows of KPIS_PER_ROW width units.

    Long labels or values (e.g. "Total Net revenue (calculated)": "159,020.80") get a
    double-width card, so numbers are never cut off at laptop widths, while the
    other cards keep their normal size."""
    rows: list[list] = [[]]
    for kpi in kpis:
        if sum(kpi_width(k) for k in rows[-1]) + kpi_width(kpi) > KPIS_PER_ROW:
            rows.append([])
        rows[-1].append(kpi)
    return [row for row in rows if row]


def _show_section(section: Section, key: str) -> None:
    with st.container(border=True):
        st.markdown(f"**{section.title}**")
        st.markdown(section.text)
        figure = charts.line_chart(section.chart) if section.kind == "line" else charts.bar_chart(section.chart)
        figure.update_layout(title=None, margin={"t": 10, "b": 10}, height=320)
        st.plotly_chart(figure, key=key, config={"displaylogo": False})
        for note in section.notes:
            st.caption(f"ℹ️ {note}")


def show_executive_summary(summary: ExecutiveSummary) -> None:
    st.markdown(f"#### {summary.headline}")

    for row in kpi_rows(summary.kpis):
        widths = [kpi_width(kpi) for kpi in row]
        widths += [1] * (KPIS_PER_ROW - sum(widths))  # empty space keeps card sizes equal
        for column, kpi in zip(st.columns(widths), row):
            column.metric(kpi.label, kpi.value, help=kpi.help or None, border=True)

    if summary.metric:
        notes = "".join(f"\n- {n}" for n in summary.metric.notes)
        st.info(
            f"🧮 **{summary.metric.label}** is calculated by the app, not a column in your "
            f"data:\n\n{summary.metric.formula}{notes}"
        )

    sections = [(s, key) for s, key in ((summary.trend, "summary_trend"), (summary.comparison, "summary_comparison")) if s]
    if sections:
        for column, (section, key) in zip(st.columns(len(sections)), sections):
            with column:
                _show_section(section, key)

    with st.container(border=True):
        st.markdown("**Data quality**")
        clean = summary.quality[:1] == ("No missing values, duplicate rows or other data-quality issues were found.",)
        lines = [f"- {'✅' if clean else '⚠️'} {note}" for note in summary.quality]
        lines += [f"- ℹ️ {note}" for note in summary.info]
        st.markdown("\n".join(lines))

    if summary.skipped:
        with st.expander("Not shown, and why"):
            st.markdown("\n".join(f"- {reason}" for reason in summary.skipped))
    st.caption(
        "Every figure on this page is calculated directly from the data with pandas. "
        "Nothing is generated by AI or estimated."
    )
